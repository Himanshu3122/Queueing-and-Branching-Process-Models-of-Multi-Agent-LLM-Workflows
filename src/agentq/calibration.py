"""Parameter estimation from execution traces (paper Sections 5.1, 10 and Discussion).

The paper does not calibrate on real traces; it names maximum-likelihood fitting with AIC model
selection and offspring-count estimation of ``m`` (with the uncertainty of Eq. (5)) as the
required next step. This module implements those estimators against a simple, documented trace
schema so they can be applied once traces exist. It has only been exercised on synthetic
traces generated by :func:`synthetic_trace` (clearly labelled non-paper data).

Trace schema (one row per *attempt*)::

    task_id: int        task identifier
    step: int           1-based step index within the task
    attempt: int        0-based attempt index within the step
    failed: bool        whether the attempt failed
    n_tool_calls: int   tool calls issued by the attempt
    llm_service: float  LLM service time of the attempt (seconds, excluding queueing)
    tool_services: list[float]  service times of its tool calls (seconds)
"""

from __future__ import annotations

import math
from collections import defaultdict
from collections.abc import Iterable, Sequence
from dataclasses import asdict, dataclass, field
from typing import Any

import numpy as np
from scipy import stats

from agentq.config import PoolConfig, SystemConfig, WorkflowConfig
from agentq.queueing import lognormal_params


@dataclass(frozen=True)
class FitResult:
    """A fitted service-time distribution."""

    family: str
    log_likelihood: float
    aic: float
    mean: float
    cv: float

    def to_dict(self) -> dict[str, float | str]:
        return asdict(self)


def fit_service_times(samples: Sequence[float]) -> list[FitResult]:
    """Fit lognormal, exponential and gamma by maximum likelihood; return sorted by AIC (best first)."""
    x = np.asarray(samples, dtype=float)
    if x.size < 10 or np.any(x <= 0):
        raise ValueError("need at least 10 strictly positive service times")
    results: list[FitResult] = []
    s, _, scale = stats.lognorm.fit(x, floc=0)
    ll = float(stats.lognorm.logpdf(x, s, 0, scale).sum())
    mean_ln = scale * math.exp(s * s / 2)
    results.append(FitResult("lognormal", ll, 2 * 2 - 2 * ll, mean_ln, math.sqrt(math.exp(s * s) - 1)))
    _, scale_e = stats.expon.fit(x, floc=0)
    ll = float(stats.expon.logpdf(x, 0, scale_e).sum())
    results.append(FitResult("exponential", ll, 2 * 1 - 2 * ll, scale_e, 1.0))
    a, _, scale_g = stats.gamma.fit(x, floc=0)
    ll = float(stats.gamma.logpdf(x, a, 0, scale_g).sum())
    results.append(FitResult("gamma", ll, 2 * 2 - 2 * ll, a * scale_g, 1 / math.sqrt(a)))
    return sorted(results, key=lambda r: r.aic)


@dataclass
class CalibrationResult:
    """Estimated structural parameters with simple uncertainty measures."""

    n_tasks: int
    n_attempts: int
    failure_prob: float
    failure_prob_se: float
    max_retries_observed: int
    mean_steps: float
    fanout_mean: float
    fanout_dispersion_index: float
    fanout_kind: str
    llm_fit: list[FitResult] = field(default_factory=list)
    tool_fit: list[FitResult] = field(default_factory=list)

    def to_dict(self) -> dict[str, Any]:
        d = asdict(self)
        d["llm_fit"] = [f.to_dict() for f in self.llm_fit]
        d["tool_fit"] = [f.to_dict() for f in self.tool_fit]
        return d

    def to_system(self, llm_servers: int, tool_servers: int, name: str = "calibrated") -> SystemConfig:
        """Build a :class:`SystemConfig` from the estimates (pool sizes must be supplied)."""
        llm, tool = self.llm_fit[0], self.tool_fit[0]
        fan = round(self.fanout_mean) if self.fanout_kind == "fixed" else self.fanout_mean
        return SystemConfig(
            name=name,
            workflow=WorkflowConfig(
                mean_steps=max(1.0, self.mean_steps),
                fanout_kind=self.fanout_kind,  # type: ignore[arg-type]
                fanout=fan,
                failure_prob=self.failure_prob,
                max_retries=self.max_retries_observed,
            ),
            llm=PoolConfig(servers=llm_servers, mean_service=llm.mean, cv=llm.cv),
            tool=PoolConfig(servers=tool_servers, mean_service=tool.mean, cv=tool.cv),
        )


def calibrate(rows: Iterable[dict[str, Any]]) -> CalibrationResult:
    """Estimate ``p``, ``n_bar``, the fan-out law and service distributions from attempt rows.

    * ``p``: failed attempts / attempts (binomial standard error reported).
    * ``n_bar``: successful tasks have a step count that is geometric with parameter
      ``1 - (1 - q) s`` after success conditioning (the tilt in Eq. (18)), so
      ``q = 1 - (1 - 1/mean_steps_successful) / s`` with ``s = 1 - p^(R+1)``.
    * fan-out: Poisson if the dispersion index (variance/mean) exceeds 0.5, else fixed.
    """
    rows = list(rows)
    if not rows:
        raise ValueError("no attempt rows supplied")
    by_task: dict[int, list[dict[str, Any]]] = defaultdict(list)
    for row in rows:
        by_task[int(row["task_id"])].append(row)
    n_att = len(rows)
    n_fail = sum(1 for r in rows if r["failed"])
    p = n_fail / n_att
    r_obs = max(int(r["attempt"]) for r in rows)
    s = 1.0 - p ** (r_obs + 1)
    succ_steps = []
    for task_rows in by_task.values():
        steps = max(int(r["step"]) for r in task_rows)
        last = [r for r in task_rows if int(r["step"]) == steps]
        if not last[-1]["failed"]:
            succ_steps.append(steps)
    if not succ_steps:
        raise ValueError("no successful tasks in trace")
    m_succ = float(np.mean(succ_steps))
    q = 1.0 - (1.0 - 1.0 / m_succ) / s
    q = min(max(q, 1e-9), 1.0)
    fan = np.array([int(r["n_tool_calls"]) for r in rows], dtype=float)
    fan_mean = float(fan.mean())
    disp = float(fan.var() / fan_mean) if fan_mean > 0 else 0.0
    llm = [float(r["llm_service"]) for r in rows]
    tools = [float(t) for r in rows for t in r["tool_services"]]
    return CalibrationResult(
        n_tasks=len(by_task),
        n_attempts=n_att,
        failure_prob=p,
        failure_prob_se=math.sqrt(p * (1 - p) / n_att),
        max_retries_observed=r_obs,
        mean_steps=1.0 / q,
        fanout_mean=fan_mean,
        fanout_dispersion_index=disp,
        fanout_kind="poisson" if disp > 0.5 else "fixed",
        llm_fit=fit_service_times(llm),
        tool_fit=fit_service_times(tools) if len(tools) >= 10 else [],
    )


def estimate_delegation(offspring_counts: Sequence[int]) -> dict[str, float]:
    """Estimate mean delegation ``m`` and the relative SE of ``E[Z] = 1/(1-m)`` (Eq. (5))."""
    x = np.asarray(offspring_counts, dtype=float)
    if x.size < 2:
        raise ValueError("need at least two offspring counts")
    m_hat = float(x.mean())
    out = {"m_hat": m_hat, "m_se": float(x.std(ddof=1) / math.sqrt(x.size)), "n": float(x.size)}
    if m_hat < 1:
        out["expected_tree_size"] = 1.0 / (1.0 - m_hat)
        out["tree_size_relative_se"] = float(x.std(ddof=1) / (math.sqrt(x.size) * (1.0 - m_hat)))
    else:
        out["expected_tree_size"] = float("inf")
        out["tree_size_relative_se"] = float("inf")
    return out


def synthetic_trace(system: SystemConfig, n_tasks: int, seed: int = 0) -> list[dict[str, Any]]:
    """Generate a SYNTHETIC attempt trace from the model's own assumptions (no queueing).

    For testing the estimators only. This is not paper data and not real agent data.
    """
    if n_tasks < 1:
        raise ValueError("n_tasks must be >= 1")
    rng = np.random.default_rng(seed)
    wf = system.workflow
    mu_l, sg_l = lognormal_params(system.llm.mean_service, system.llm.cv)
    mu_t, sg_t = lognormal_params(system.tool.mean_service, system.tool.cv)
    rows: list[dict[str, Any]] = []
    for task in range(n_tasks):
        n_steps = int(rng.geometric(wf.q))
        for step in range(1, n_steps + 1):
            step_ok = False
            for attempt in range(wf.max_retries + 1):
                k = int(rng.poisson(wf.fanout)) if wf.fanout_kind == "poisson" else int(wf.fanout)
                failed = bool(rng.random() < wf.failure_prob)
                rows.append(
                    {
                        "task_id": task,
                        "step": step,
                        "attempt": attempt,
                        "failed": failed,
                        "n_tool_calls": k,
                        "llm_service": float(rng.lognormal(mu_l, sg_l)),
                        "tool_services": [float(v) for v in rng.lognormal(mu_t, sg_t, k)],
                    }
                )
                if not failed:
                    step_ok = True
                    break
            if not step_ok:
                break
    return rows
