"""Generate the manuscript's tables, figure data and number macros from the result JSONs.

Every number in the real-data manuscript comes from ``results/real/full/*.json`` through this script,
so text, tables and figures cannot drift from the results.

Usage: python scripts/make_paper_assets.py [--results results/real/full] [--out paper/SIMPAT/generated]
"""

# ruff: noqa: E501  (long f-strings that emit LaTeX table rows read better unbroken)
from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

import numpy as np
from scipy import stats

ENVS = {"os": "OS", "db": "DB", "alfworld": "ALFWorld", "webshop": "WebShop", "kg": "KG", "mixed": "Mixed"}


def load(results: Path, name: str) -> dict[str, Any]:
    return json.loads((results / f"{name}.json").read_text(encoding="utf-8"))["results"]


def pct(x: float | None, signed: bool = True, digits: int = 0) -> str:
    if x is None:
        return "--"
    v = 100 * x
    s = f"{v:+.{digits}f}" if signed else f"{v:.{digits}f}"
    return s.replace("-", "$-$") if signed else s


def num(x: float, digits: int = 1) -> str:
    return f"{x:,.{digits}f}".replace(",", "{,}")


class Macros:
    def __init__(self) -> None:
        self.lines: list[str] = []

    def add(self, name: str, value: str) -> None:
        self.lines.append(f"\\newcommand{{\\{name}}}{{{value}}}")

    def text(self) -> str:
        return "% generated by scripts/make_paper_assets.py -- do not edit\n" + "\n".join(self.lines) + "\n"


def table(cols: str, header: str, rows: list[str], label: str, caption: str) -> str:
    body = "\n".join(r + r" \\" for r in rows)
    return (
        "% generated by scripts/make_paper_assets.py -- do not edit\n"
        "\\begin{table}[!htbp]\n\\centering\\small\n"
        f"\\caption{{{caption}}}\\label{{{label}}}\n"
        "\\begin{adjustbox}{max width=\\linewidth}\n"
        f"\\begin{{tabular}}{{{cols}}}\n\\toprule\n{header} \\\\\n\\midrule\n{body}\n\\bottomrule\n"
        "\\end{tabular}\n\\end{adjustbox}\n\\end{table}\n"
    )


