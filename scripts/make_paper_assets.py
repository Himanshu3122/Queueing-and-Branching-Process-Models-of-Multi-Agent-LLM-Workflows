def fig_rule(r: Path, out: Path, m: Macros) -> None:
    v = load(r, "real_azure2024")["surge_vs_error"]
    pts = [
        (float(rho) * h["peak_ratio_1min"], 100 * h["error"]["p99"], h["service"])
        for rho, s in v.items()
        for h in s["hours"]
    ]
    for service in ("code", "conversation"):
        lines = ["x y"] + [f"{x:.4f} {y:.2f}" for x, y, s in pts if s == service]
        (out / f"fig_rule_{service}.dat").write_text("\n".join(lines) + "\n")
    x = np.array([p[0] for p in pts])
    y = np.array([p[1] for p in pts])
    rho, pval = stats.spearmanr(x, y)
    low = x < 0.95
    m.add("RuleSpearman", f"{rho:.2f}".replace("-", "$-$"))
    m.add("RulePvalue", f"{pval:.0e}".replace("e-", r"\times10^{-").replace("e+", r"\times10^{") + "}")
    m.add("RuleN", str(x.size))
    m.add("RuleLowN", str(int(low.sum())))
    m.add("RuleLowMinPnn", f"{y[low].min():+.0f}".replace("-", "$-$"))
    m.add("RuleLowMaxPnn", f"{y[low].max():+.0f}")
    m.add("RuleHighMinPnn", f"{y[x >= 1.0].min():+.0f}".replace("-", "$-$"))


def fig_stepfix(r: Path, out: Path) -> None:
    g = load(r, "real_validation")["environments"]
    e = load(r, "real_validation_empirical")["environments"]
    lines = ["idx label geo emp"]
    for i, env in enumerate(ENVS):
        rg = next(x for x in g[env]["rows"] if x["rho_llm"] == 0.5)["error"]["replay_poisson"]["p99"]
        re_ = next(x for x in e[env]["rows"] if x["rho_llm"] == 0.5)["error"]["replay_poisson"]["p99"]
        lines.append(f"{i} {ENVS[env]} {100 * rg:.2f} {100 * re_:.2f}")
    (out / "fig_stepfix.dat").write_text("\n".join(lines) + "\n")


def misc_macros(r: Path, m: Macros) -> None:
    fan = load(r, "real_fanout")["laws"]
    m.add("BFCLOneCall", pct(fan["live_all"]["pmf"]["1"], False))
    m.add("BFCLForkMean", num(fan["live_parallel"]["mean"], 2))
    regimes = load(r, "real_fanout")["regimes"]
    tool = [row for key in ("live_all/tool_bound", "live_parallel/tool_bound") for row in regimes[key]["rows"]]
    worst_best = max(abs(row["error"]["poisson_batch"]["p99"]) for row in tool)
    worst_fixed = min(row["error"]["fixed"]["p99"] for row in tool)
    m.add("FanoutBestWorst", pct(worst_best, False, 1))
    m.add("FanoutFixedWorst", pct(worst_fixed, True, 1))
    ww = load(r, "real_multiagent")["delegation_magentic_one"]
    m.add("WWDelegMean", num(ww["delegations_per_task"]["mean"]))
    m.add("WWGWm", num(ww["galton_watson_estimate"]["m_hat"], 2))
    m.add("WWRealPnn", num(ww["tree_size"]["p99"], 0))
    m.add("WWGWPnn", num(ww["galton_watson_implied_tree_size"]["p99"], 0))
    m.add(
        "WWAfterError",
        pct(
            load(r, "real_multiagent")["decisive_errors"]["Hand-Crafted"]["fraction_of_agent_turns_after_error"][
                "mean"
            ],
            False,
        ),
    )
    lt = load(r, "real_burstgpt")["parts"]["part3_110d"]["latency"]["by_model"]["GPT-4"]
    m.add("BGGPTfourDecode", num(lt["fitted"]["decode_ms_per_token"], 1))
    m.add("BGGPTfourMedTok", num(lt["measured_ms_per_output_token_median"], 1))
    bgf = load(r, "real_burstgpt")["parts"]
    m.add("BGFailAfterFailOne", pct(bgf["part1_61d"]["failures"]["fail_after_fail"]["rate"], False))
    m.add("BGFailAfterFailThree", pct(bgf["part3_110d"]["failures"]["fail_after_fail"]["rate"], False))
    cal = load(r, "real_calibration")["azure_arrivals"]
    m.add("AzIDCthreehundred", num(cal["index_of_dispersion"]["300.0"], 0))


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--results", default="results/real/full")
    ap.add_argument("--out", default="paper/SIMPAT/generated")
    a = ap.parse_args()
    r, out = Path(a.results), Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    m = Macros()
    for name, fn in (
        ("tab_steps", tab_steps),
        ("tab_failures", tab_failures),
        ("tab_arrivals", tab_arrivals),
        ("tab_replay", tab_replay),
        ("tab_mast", tab_mast),
        ("tab_swegym", tab_swegym),
    ):
        (out / f"{name}.tex").write_text(fn(r, m), encoding="utf-8")
    fig_rule(r, out, m)
    fig_stepfix(r, out)
    misc_macros(r, m)
    (out / "numbers.tex").write_text(m.text(), encoding="utf-8")
    print(f"wrote {len(list(out.iterdir()))} files to {out}")


if __name__ == "__main__":
    main()
