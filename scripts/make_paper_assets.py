def tab_steps(r: Path, m: Macros) -> str:
    cal = load(r, "real_calibration")["environments"]
    swe = load(r, "real_swegym")["groups"]
    mast = load(r, "real_mast")["zero_load_latency"]
    bg = load(r, "real_burstgpt")["parts"]["part3_110d"]["sessions"]["turns"]
    rows = []
    for env in ("os", "db", "alfworld", "webshop", "kg", "mixed"):
        s = cal[env]["steps"]
        rows.append(
            f"AgentInstruct {ENVS[env]} & {cal[env]['n_trajectories']:,} & {num(s['mean'])} & {num(s['var'])} & "
            f"{num(s['geometric_var'])} & {num(s['var_ratio_to_geometric'], 2)} & {num(s['ks_distance_to_geometric'], 2)}"
        )
    s = swe["all"]["resolved_steps"]
    rows.append(
        f"SWE-Gym, resolved runs & {int(round(swe['all']['resolved']['rate'] * swe['all']['runs'])):,} & {num(s['mean'])} & "
        f"{num(s['var'])} & {num(s['geometric_var'])} & {num(s['var_ratio_to_geometric'], 2)} & "
        f"{num(s['ks_distance_to_geometric'], 2)}"
    )
    for g in ("MetaGPT/GPT-4o", "ChatDev/GPT-4o", "ChatDev/Qwen"):
        s = mast[g]["steps"]
        rows.append(
            f"MAST {g} & {mast[g]['runs']} & {num(s['mean'])} & {num(s['var'])} & {num(s['geometric_var'])} & "
            f"{num(s['var_ratio_to_geometric'], 3)} & {num(s['ks_distance_to_geometric'], 2)}"
        )
    rows.append(
        f"BurstGPT chat sessions (human) & {load(r, 'real_burstgpt')['parts']['part3_110d']['sessions']['sessions']:,} & "
        f"{num(bg['mean'])} & {num(bg['var'])} & {num(bg['geometric_var'])} & {num(bg['var_ratio_to_geometric'], 2)} & "
        f"{num(bg['ks_distance_to_geometric'], 2)}"
    )
    m.add("KGStepVar", num(cal["kg"]["steps"]["var"]))
    m.add("KGGeoVar", num(cal["kg"]["steps"]["geometric_var"], 0))
    return table(
        "lrrrrrr",
        r"Workload & Tasks & Mean & Var. & Geom.\ var. & Var.\ ratio & KS",
        rows,
        "tab:steps",
        "Step counts per task against the geometric law with the same mean (Var.\\ ratio = observed / "
        "geometric variance; KS = Kolmogorov--Smirnov distance between the CDFs).",
    )


def tab_failures(r: Path, m: Macros) -> str:
    cal = load(r, "real_calibration")["environments"]
    swe = load(r, "real_swegym")["groups"]["all"]
    ma = load(r, "real_multiagent")["tool_failures_captainagent"]
    rows = []
    for env in ("os", "db", "kg"):
        c, f = cal[env]["calibration"], cal[env]["failures"]
        rows.append(
            f"AgentInstruct {ENVS[env]} (action errors) & {num(100 * c['failure_prob'], 1)} & "
            f"{num(100 * f['p_fail_after_fail'], 1)} & {num(100 * f['p_fail_after_success'], 1)} & --"
        )
    for key, label in (("failures_strict", "tool-usage errors"), ("failures_broad", "incl.\\ non-zero exits")):
        f = swe[key]
        rows.append(
            f"SWE-Gym ({label}) & {num(100 * f['failure']['rate'], 1)} & {num(100 * f['fail_after_fail']['rate'], 1)} & "
            f"{num(100 * f['fail_after_success']['rate'], 1)} & {num(f['odds_ratio'], 2)}"
        )
    rows.append(
        f"Who\\&When CaptainAgent (code exec.) & {num(100 * ma['failure']['rate'], 1)} & "
        f"{num(100 * ma['fail_after_fail']['rate'], 1)} & {num(100 * ma['fail_after_success']['rate'], 1)} & "
        f"{num(ma['fisher_odds_ratio'], 2)} ($p={ma['fisher_pvalue']:.2f}$)"
    )
    m.add("SWEStrictOR", num(swe["failures_strict"]["odds_ratio"], 1))
    m.add("SWEBroadOR", num(swe["failures_broad"]["odds_ratio"], 2))
    m.add("WWFisherP", f"{ma['fisher_pvalue']:.2f}")
    return table(
        "lrrrr",
        r"Source & $p$ (\%) & P(fail$\mid$fail) & P(fail$\mid$ok) & Odds ratio",
        rows,
        "tab:failures",
        "Per-attempt failure rate and dependence on the previous attempt of the same task.",
    )


